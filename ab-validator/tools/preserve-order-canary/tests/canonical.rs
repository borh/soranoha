fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

#[test]
fn convert_and_serialize_parser_ir_is_canonical_under_preserve_order() {
    let repo = repo_root();
    // The mapping loaded below (`aat-to-parser-ir-mapping-v1.json`) declares
    // `source_aat_version: 1`; `MappingDocument::preflight` requires the
    // loaded AAT schema version to match, so this canary (whose fixture AAT
    // document is itself `"version": 1`) loads the v1 schema tuple. (v2
    // fails preflight with "mapping/schema tuple mismatch".) The test asserts
    // that with preserve_order active, canonical (sorted-key) parser-IR
    // serialization does not depend on map ordering.
    let schemas = ab_aat_to_parser_ir::SchemaSet::load_for_aat_version(&repo, 1).unwrap();
    let mapping = ab_aat_to_parser_ir::MappingDocument::from_path(
        &repo.join("data/aat-to-parser-ir-mapping-v1.json"),
    )
    .unwrap();

    let aat = json!({
        "version": 1,
        "work_id": "canary",
        "meta": {
            "adapter": "fixture",
            "adapter_version": "fixture 0.1.0",
            "source_encoding": "utf-8",
            "source_hash": "sha256:6666666666666666666666666666666666666666666666666666666666666666",
            "parse_complete": true,
            "warnings": []
        },
        "blocks": [{"kind": "paragraph", "content": [{"kind": "text", "value": "A"}]}]
    });

    let output = ab_aat_to_parser_ir::convert(ab_aat_to_parser_ir::ConversionRequest {
        aat,
        mapping,
        schemas,
        options: ab_aat_to_parser_ir::ConversionOptions::default(),
    })
    .unwrap();

    let text = ab_aat_to_parser_ir::to_canonical_json_pretty(output.parser_ir).unwrap();
    assert_eq!(text, EXPECTED_PARSER_IR);
}
